"""
Utility definitions for handling a single simulation run and its conversion to and from
HDF5 files.

The :class:`Simulation` dataclass groups together the simulation identifier, its
parameters, the stimulus set, and the output spike map.  It implements the
:class:`~converters.schema.hdf5_serializable.HDF5Serializable` interface which
provides ``to_hdf5`` and ``from_hdf5`` methods for (de)serialisation.

Typical usage::

    sim = Simulation(simulation_id="001")
    sim.to_hdf5(h5_root_group)

    # Later …
    loaded_sim = Simulation.from_hdf5(h5_root_group["Sim_001"])
"""

from dataclasses import dataclass, field

import h5py

from converters.schema.hdf5_serializable import HDF5Serializable
from converters.schema.simulation_parameters import SimulationParameters
from converters.schema.spike_map import SpikeMap
from converters.schema.stimulus_set import StimulusSet
from converters.utils.dataset_helpers import make_group


@dataclass
class Simulation(HDF5Serializable):
    """Container for a single simulation run.

    The hierarchy inside the HDF5 group created for a simulation is::

        <parent>/<Sim_<simulation_id>>/
            Parameters/
            Stimulus/
            OutputSpike/

    Attributes
    ----------
    simulation_id: str
        Identifier of the simulation (e.g. ``"001"``).  It is used to name the
        top‑level HDF5 group as ``Sim_<simulation_id>``.
    parameters: SimulationParameters
        Configuration parameters that were used for the run.
    stimulus: StimulusSet
        The stimulus set presented during the simulation.
    output_spike: SpikeMap
        Spike data generated by the simulation.
    """

    simulation_id: str
    parameters: SimulationParameters = field(default_factory=SimulationParameters)
    stimulus: StimulusSet = field(default_factory=StimulusSet)
    output_spike: SpikeMap = field(default_factory=SpikeMap)

    def to_hdf5(self, parent: h5py.Group) -> None:
        """Serialise the simulation into an HDF5 hierarchy.

        The method creates a group named ``Sim_<simulation_id>`` under ``parent``
        and populates three sub‑groups (``Parameters``, ``Stimulus`` and
        ``OutputSpike``) by delegating to the respective ``to_hdf5`` methods of the
        stored objects.

        Parameters
        ----------
        parent: h5py.Group
            The HDF5 group that will contain the simulation group.

        Raises
        ------
        TypeError
            If ``parent`` is not an instance of :class:`h5py.Group`.
        OSError
            If the HDF5 file cannot be written (e.g., file is read‑only).
        """
        sim_grp = make_group(parent, f"Sim_{self.simulation_id}")

        # ---- parameters -------------------------------------------------
        param_grp = make_group(sim_grp, "Parameters")
        self.parameters.to_hdf5(param_grp)

        # ---- stimulus ---------------------------------------------------
        stim_grp = make_group(sim_grp, "Stimulus")
        self.stimulus.to_hdf5(stim_grp)

        # ---- output spikes ----------------------------------------------
        spike_grp = make_group(sim_grp, "OutputSpike")
        self.output_spike.to_hdf5(spike_grp)

    @classmethod
    def from_hdf5(cls, grp: h5py.Group) -> "Simulation":
        """Recreate a :class:`Simulation` instance from an HDF5 group.

        The supplied group must correspond to a ``Sim_<id>`` group created by
        :meth:`to_hdf5`.  The method extracts the simulation identifier from the
        group name and loads the ``Parameters``, ``Stimulus`` and ``OutputSpike``
        sub‑groups using their respective ``from_hdf5`` constructors.

        Parameters
        ----------
        grp: h5py.Group
            The HDF5 group representing a single simulation (named ``Sim_<id>``).

        Returns
        -------
        Simulation
            A new instance populated with data read from ``grp``.

        Raises
        ------
        KeyError
            If any of the expected sub‑groups (``parameters``, ``Stimulus``,
            ``OutputSpike``) are missing.
        TypeError
            If ``grp`` is not an instance of :class:`h5py.Group`.
        ValueError
            If the group name does not contain a valid simulation identifier.
        OSError
            If the underlying HDF5 file cannot be read.
        """
        # ``grp`` is ``Sim_<id>`` – extract the numeric part for the ID.
        sim_id = grp.name.split("/")[-1].replace("Sim_", "")
        if not sim_id:
            raise ValueError("Simulation group name does not contain an identifier.")

        params = SimulationParameters.from_hdf5(grp["parameters"])
        stim = StimulusSet.from_hdf5(grp["Stimulus"])
        spikes = SpikeMap.from_hdf5(grp["OutputSpike"])
        return cls(simulation_id=sim_id, parameters=params, stimulus=stim, output_spike=spikes)
