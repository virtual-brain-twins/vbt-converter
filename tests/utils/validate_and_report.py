#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
validate_and_report.py

Utility to

1. verify that a .npz file generated by `convert.py` is well‑formed,
2. optionally perform a few sanity checks on the numerical data,
3. write a human‑readable HTML report that lists the contents and
   prints a success message.

Usage
-----
    python validate_and_report.py -i path/to/output.npz -o report.html

The script exits with status 0 on success, 1 on validation failure.
"""

import argparse
import datetime
import html
import pathlib
import sys

import numpy as np


def _format_array(name: str, arr: np.ndarray) -> str:
    """Return an HTML <tr> describing *arr*."""
    # Convert potentially huge min / max values to readable strings
    arr_min = np.min(arr) if arr.size else "n/a"
    arr_max = np.max(arr) if arr.size else "n/a"
    # For very large arrays we do not dump the data itself, just the shape.
    shape = "×".join(map(str, arr.shape))
    dtype = str(arr.dtype)

    # Escape the name for safety (unlikely needed but good practice)
    name = html.escape(name)

    return f"""
    <tr>
        <td><code>{name}</code></td>
        <td>{shape}</td>
        <td>{dtype}</td>
        <td>{arr_min:.6g}</td>
        <td>{arr_max:.6g}</td>
    </tr>
    """


# ----------------------------------------------------------------------
# Validation logic
# ----------------------------------------------------------------------
def validate_npz(npz_path: pathlib.Path) -> dict:
    """
    Load *npz_path* and run a series of consistency checks.
    Returns a dictionary with all loaded arrays (for later HTML rendering).

    Raises
    ------
    ValueError
        If any of the required keys are missing or shapes are inconsistent.
    """
    required_keys = {
        # data arrays
        "x": "firing‑rate tensor (npoints, nt, npop)",
        "u": "stimulus tensor (npoints, nt, 1)",
        "theta": "parameter tensor (npoints, nparams)",
        # meta data
        "names_x": "list of population names (len = npop)",
        "names_theta": "list of short parameter names (len = nparams)",
        "dt": "time‑bin size (float)",
        # normalisation statistics
        "mu_x": "mean of x (broadcastable to x)",
        "sd_x": "std of x (broadcastable to x)",
        "mu_u": "mean of u",
        "sd_u": "std of u",
        "mu_theta": "mean of theta",
        "sd_theta": "std of theta",
    }

    # ------------------------------------------------------------------
    # 1️⃣ Load the file
    # ------------------------------------------------------------------
    if not npz_path.is_file():
        raise FileNotFoundError(f"File not found: {npz_path}")

    try:
        archive = np.load(npz_path, allow_pickle=False)
    except Exception as exc:
        raise ValueError(f"Could not read {npz_path}: {exc}") from exc

    # ------------------------------------------------------------------
    # 2️⃣ Check the presence of all required keys
    # ------------------------------------------------------------------
    missing = [k for k in required_keys if k not in archive]
    if missing:
        raise ValueError(f"Missing required keys in {npz_path.name}: {missing}")

    # ------------------------------------------------------------------
    # 3️⃣ Pull everything into a plain dict for easier handling later
    # ------------------------------------------------------------------
    data = {k: archive[k] for k in required_keys}
    # Convert byte‑strings (the script stored them as UTF‑8) to normal Python strings
    if isinstance(data["names_x"], np.ndarray) and data["names_x"].dtype.kind == "U":
        data["names_x"] = data["names_x"].tolist()
    if isinstance(data["names_theta"], np.ndarray) and data["names_theta"].dtype.kind == "U":
        data["names_theta"] = data["names_theta"].tolist()

    # ------------------------------------------------------------------
    # 4️⃣ Shape sanity checks
    # ------------------------------------------------------------------
    npoints, nt, npop = data["x"].shape
    if data["u"].shape != (npoints, nt, 1):
        raise ValueError(
            f"`u` has shape {data['u'].shape} but expected ({npoints}, {nt}, 1)"
        )
    if data["theta"].shape != (npoints, len(data["names_theta"])):
        raise ValueError(
            f"`theta` shape {data['theta'].shape} does not match "
            f"npoints={npoints} and nparams={len(data['names_theta'])}"
        )
    if len(data["names_x"]) != npop:
        raise ValueError(
            f"`names_x` length {len(data['names_x'])} does not match npop={npop}"
        )
    # The normalisation statistics must be broadcastable to the data arrays.
    # A simple way to check that is to attempt a broadcast and see if NumPy raises.
    try:
        _ = (data["x"] - data["mu_x"]) / data["sd_x"]
    except Exception as exc:
        raise ValueError(f"`mu_x` / `sd_x` are not broadcastable to `x`: {exc}") from exc

    try:
        _ = (data["u"] - data["mu_u"]) / data["sd_u"]
    except Exception as exc:
        raise ValueError(f"`mu_u` / `sd_u` are not broadcastable to `u`: {exc}") from exc

    try:
        _ = (data["theta"] - data["mu_theta"]) / data["sd_theta"]
    except Exception as exc:
        raise ValueError(f"`mu_theta` / `sd_theta` are not broadcastable to `theta`: {exc}") from exc

    # ------------------------------------------------------------------
    # 5️⃣ Basic numeric sanity (optional but helpful)
    # ------------------------------------------------------------------
    # No NaNs or infinities in any of the main tensors?
    for name in ("x", "u", "theta"):
        arr = data[name]
        if np.isnan(arr).any():
            raise ValueError(f"`{name}` contains NaN values.")
        if np.isinf(arr).any():
            raise ValueError(f"`{name}` contains infinite values.")

    # All standard‑deviations must be > 0 (otherwise the normalisation would have divided by zero)
    for name in ("sd_x", "sd_u", "sd_theta"):
        if np.any(data[name] <= 0):
            raise ValueError(f"`{name}` must be strictly positive; found non‑positive entries.")

    # If we get here, everything looks OK.
    return data


# ----------------------------------------------------------------------
# HTML report generation
# ----------------------------------------------------------------------
HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>NPZ Validation Report – {filename}</title>
    <style>
        body {{font-family: Arial, Helvetica, sans-serif; margin: 2rem;}}
        h1 {{color: #333;}}
        .banner {{padding: 1rem; border-radius: 8px; margin-bottom: 2rem;}}
        .success {{background-color: #e6ffed; color: #2e7d32;}}
        .error   {{background-color: #ffebee; color: #c62828;}}
        table {{border-collapse: collapse; width: 100%; margin-top: 1rem;}}
        th, td {{border: 1px solid #ddd; padding: 0.5rem; text-align: left;}}
        th {{background-color: #f2f2f2;}}
        code {{background: #f9f9f9; padding: 2px 4px; border-radius: 4px;}}
    </style>
</head>
<body>
    <h1>NPZ Validation Report</h1>
    <p><strong>File:</strong> {filename}<br>
       <strong>Generated on:</strong> {timestamp}</p>

    <div class="banner {status_class}">
        <strong>{status_message}</strong>
    </div>

    {content}
</body>
</html>
"""


def build_content(data: dict) -> str:
    """
    Produce the HTML fragment that describes the contents of the NPZ.
    """
    sections = []

    # --------------------------------------------------------------
    # 1️⃣ General meta‑information
    # --------------------------------------------------------------
    meta_table = f"""
    <h2>Meta‑information</h2>
    <table>
        <tr><th>Key</th><th>Value</th></tr>
        <tr><td><code>dt</code></td><td>{data['dt']}</td></tr>
        <tr><td><code>names_x (populations)</code></td><td>{html.escape(str(data['names_x']))}</td></tr>
        <tr><td><code>names_theta (parameters)</code></td><td>{html.escape(str(data['names_theta']))}</td></tr>
    </table>
    """
    sections.append(meta_table)

    # --------------------------------------------------------------
    # 2️⃣ Normalisation statistics
    # --------------------------------------------------------------
    stats = {
        "mu_x": data["mu_x"],
        "sd_x": data["sd_x"],
        "mu_u": data["mu_u"],
        "sd_u": data["sd_u"],
        "mu_theta": data["mu_theta"],
        "sd_theta": data["sd_theta"],
    }
    stats_rows = "".join(
        f"<tr><td><code>{k}</code></td><td>{np.array(v).tolist()}</td></tr>"
        for k, v in stats.items()
    )
    stats_table = f"""
    <h2>Normalisation statistics</h2>
    <table>
        <tr><th>Statistic</th><th>Value (broadcastable)</th></tr>
        {stats_rows}
    </table>
    """
    sections.append(stats_table)

    # --------------------------------------------------------------
    # 3️⃣ Large data arrays – only a summary (shape, dtype, min, max)
    # --------------------------------------------------------------
    array_section = """
    <h2>Data tensors (summary)</h2>
    <table>
        <tr><th>Name</th><th>Shape</th><th>Dtype</th><th>Min</th><th>Max</th></tr>
    """
    for name in ("x", "u", "theta"):
        array_section += _format_array(name, data[name])
    array_section += "</table>"
    sections.append(array_section)

    # --------------------------------------------------------------
    # 4️⃣ Optional: a quick visualisation of the first point (if desired)
    # --------------------------------------------------------------
    # (We keep it optional because plotting within pure HTML is out of scope.)
    # You could embed a base‑64 PNG later if you want.

    return "\n".join(sections)


def write_html_report(output_path: pathlib.Path, *, data: dict, success: bool, error_msg: str = None):
    """Render and write the final HTML file."""
    filename = output_path.name
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    if success:
        status_class = "success"
        status_message = "✅ Validation successful"
        content = build_content(data)
    else:
        status_class = "error"
        status_message = f"❌ Validation failed – {html.escape(error_msg)}"
        content = "<p>No further information is shown because the file did not pass validation.</p>"

    html_text = HTML_TEMPLATE.format(
        filename=html.escape(str(filename)),
        timestamp=timestamp,
        status_class=status_class,
        status_message=status_message,
        content=content,
    )

    output_path.write_text(html_text, encoding="utf-8")
    print(f"HTML report written to: {output_path}")


# ----------------------------------------------------------------------
# Main CLI
# ----------------------------------------------------------------------
def main() -> int:
    parser = argparse.ArgumentParser(
        description="Validate a .npz file generated by convert.py and emit an HTML report."
    )
    parser.add_argument("-i", "--input", required=True, type=pathlib.Path,
                        help="Path to the .npz file to validate.")
    parser.add_argument("-o", "--output", type=pathlib.Path, default=pathlib.Path("validation_report.html"),
                        help="Destination HTML file (default: validation_report.html).")
    args = parser.parse_args()

    try:
        data = validate_npz(args.input)
        write_html_report(args.output, data=data, success=True)
        return 0
    except Exception as exc:
        # In case of any problem we still produce a tiny report that tells the user what went wrong.
        write_html_report(args.output, data={}, success=False, error_msg=str(exc))
        sys.stderr.write(f"ERROR: {exc}\n")
        return 1


if __name__ == "__main__":
    sys.exit(main())
